# Motifs répétitifs.
PATTERNS = [
    (r"^Convert to (.+) images$", r"Convertir en images \1"),
    (r"^Convert to Word \(DOCX\)$", "Convertir en Word (DOCX)"),
    (r"^Convert to (.+)$", r"Convertir en \1"),
    (r"^(Image|Document) → (\.\w+)$", r"\1 → \2"),
]

def translate(key):
    if key in FR: return FR[key]
    for pattern, repl in PATTERNS:
        if re.match(pattern, key): return re.sub(pattern, repl, key)
    return None

def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"')

keys = [k.rstrip("\n") for k in open("/tmp/convertdock-keys.txt", encoding="utf-8") if k.strip()]
lines = ["/* Traduction française de ConvertDock — générée par Scripts/fr-translations.py */", ""]
missing = []
for key in keys:
    value = translate(key)
    if value is None: missing.append(key); continue
    lines.append(f'"{esc(key)}" = "{esc(value)}";')
open("Resources/fr.lproj/Localizable.strings", "w", encoding="utf-8").write("\n".join(lines) + "\n")
for k in missing: print("sans traduction :", k)
print(f"{len(keys) - len(missing)}/{len(keys)} traductions écrites")
